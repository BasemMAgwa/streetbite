class Vendor {
  const Vendor({
    required this.id,
    required this.name,
    required this.city,
    required this.cuisine,
    required this.rating,
    required this.latitude,
    required this.longitude,
  });

  final String id;
  final String name;
  final String city;
  final String cuisine;
  final double rating;
  final double latitude;
  final double longitude;
}
